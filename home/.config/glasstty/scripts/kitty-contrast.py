#!/usr/bin/env python3
"""kitty-contrast.py — pywal colours for kitty, with guaranteed contrast.

pywal's palette comes from the wallpaper and nothing guarantees that its
colours read well on its own background (a dark blue `color4` on a dark
background is common). The terminal is also translucent here, which makes it
worse. So every colour is nudged in lightness (keeping its hue) until it
reaches a minimum WCAG contrast against the background:

    foreground ............ 7.0 : 1   (body text)
    colours 1-7, 9-15 ..... 4.5 : 1   (prompts, ls, syntax)
    colour 8 .............. 3.0 : 1   (comments, autosuggestions: meant to be dim)

The background used for the maths is pywal's, slightly darkened, standing in
for the translucent terminal over a blurred wallpaper.

Writes ~/.cache/wal/colors-kitty-contrast.conf (included by kitty.conf).
Run by set-wallpaper.sh after pywal, before kitty is told to reload.
"""

import colorsys
import json
import os
import sys

HOME = os.path.expanduser("~")
SRC = os.path.join(HOME, ".cache", "wal", "colors.json")
OUT = os.path.join(HOME, ".cache", "wal", "colors-kitty-contrast.conf")


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def hexs(c):
    return "#" + "".join(f"{max(0, min(255, round(v * 255))):02x}" for v in c)


def lum(c):
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = c
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def contrast(a, b):
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def ensure(color, bg, target):
    """Move `color`'s lightness away from the background until it reaches
    `target` contrast; saturation is eased a little so light tints stay clean."""
    c = rgb(color)
    if contrast(c, bg) >= target:
        return hexs(c)
    h, l, s = colorsys.rgb_to_hls(*c)
    up = lum(bg) < 0.5          # dark background: go lighter
    for _ in range(100):
        l = min(1.0, l + 0.01) if up else max(0.0, l - 0.01)
        if up:
            s = max(0.0, s - 0.002)
        out = colorsys.hls_to_rgb(h, l, s)
        if contrast(out, bg) >= target or l in (0.0, 1.0):
            return hexs(out)
    return hexs(c)


def main():
    try:
        pal = json.load(open(SRC, encoding="utf-8"))
    except (OSError, ValueError):
        return 1
    sp, c = pal["special"], pal["colors"]
    bg_hex = sp["background"]
    bg = rgb(bg_hex)
    # The terminal is translucent over a blurred wallpaper: measure against a
    # slightly darker (or lighter, on a light theme) version of the background.
    h, l, s = colorsys.rgb_to_hls(*bg)
    ref = colorsys.hls_to_rgb(h, max(0.0, l - 0.04) if l < 0.5 else min(1.0, l + 0.04), s)

    fg = ensure(sp["foreground"], ref, 7.0)
    cols = {}
    for i in range(16):
        key = f"color{i}"
        if i in (0,):
            cols[key] = c[key]                      # black stays black (background-ish)
        elif i == 8:
            cols[key] = ensure(c[key], ref, 3.0)
        else:
            cols[key] = ensure(c[key], ref, 4.5)
    accent = cols["color4"]

    lines = [
        "# Generated by kitty-contrast.py from pywal (contrast-checked). Do not edit.",
        f"background {bg_hex}",
        f"foreground {fg}",
        f"cursor {fg}",
        f"cursor_text_color {bg_hex}",
        f"selection_background {accent}",
        f"selection_foreground {bg_hex}",
        f"url_color {cols['color6']}",
        f"active_border_color {accent}",
        f"inactive_border_color {cols['color8']}",
        f"active_tab_background {accent}",
        f"active_tab_foreground {bg_hex}",
        f"inactive_tab_background {bg_hex}",
        f"inactive_tab_foreground {cols['color8']}",
        f"tab_bar_background {bg_hex}",
    ] + [f"{k} {v}" for k, v in cols.items()]
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, OUT)
    if "-v" in sys.argv:
        for k in ["foreground"] + [f"color{i}" for i in range(1, 16)]:
            old = sp["foreground"] if k == "foreground" else c[k]
            new = fg if k == "foreground" else cols[k]
            print(f"{k:10} {old} {contrast(rgb(old), ref):5.2f}  ->  {new} {contrast(rgb(new), ref):5.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
