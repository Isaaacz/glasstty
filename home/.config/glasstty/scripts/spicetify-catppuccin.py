#!/usr/bin/env python3
# Generates a [pywal] flavour for the Catppuccin spicetify theme
# (github.com/catppuccin/spicetify, MIT, copied into
# ~/.config/spicetify/Themes/catppuccin) from the pywal palette.
#
# Catppuccin's look comes from its layering: base, a darker mantle (sidebar)
# and crust (player bar), lighter surface0..2 for cards and hovers, overlay0..2
# for buttons, and soft pastel accents. Here every layer is built from the
# wallpaper's background (same hue, stepped lightness), and the pastels from
# the palette's colours, lifted to the light, gently saturated tone Catppuccin
# uses. `text` (titles, active controls) is the pastel accent, as in
# Catppuccin with an accent picked; `subtext` is the readable foreground.
#
# Only the [pywal] block of color.ini is inserted/replaced; the stock flavours
# (mocha, frappe...) stay, so `spicetify config color_scheme mocha` still works.
#
# Usage: spicetify-catppuccin.py [path/to/color.ini]
import colorsys
import json
import os
import re
import sys

HOME = os.path.expanduser("~")
SRC = os.path.join(HOME, ".cache/wal/colors.json")
OUT = sys.argv[1] if len(sys.argv) > 1 else \
    os.path.join(HOME, ".config/spicetify/Themes/catppuccin/color.ini")

try:
    d = json.load(open(SRC))
except (OSError, ValueError) as e:
    sys.stderr.write("no colors.json: %s\n" % e)
    sys.exit(1)
sp, c = d["special"], d["colors"]


def hls(h):
    h = h.lstrip("#")
    return colorsys.rgb_to_hls(*(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)))


def hx(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h % 1, max(0, min(1, l)), max(0, min(1, s)))
    return "%02X%02X%02X" % (round(r * 255), round(g * 255), round(b * 255))


# --- the background ramp -------------------------------------------------------
bh, bl, bs = hls(sp["background"])
bs = min(bs, 0.35)               # keep the layers calm, like Catppuccin's
bl = min(max(bl, 0.07), 0.16)    # a dark base the layers can step up from


def layer(dl, ds=0.0):
    return hx(bh, bl + dl, bs * (1 - ds))


# --- the accent ---------------------------------------------------------------
def chroma(hexa):
    _, l, s = hls(hexa)
    return s * (1 - abs(2 * l - 1))


# color4 is the system accent; when it is almost grey, take the most colourful
# of color1..6 (same rule as folders-pywal.py).
acc = c["color4"] if hls(c["color4"])[2] >= 0.25 else \
    max((c[f"color{i}"] for i in range(1, 7)), key=chroma)
ah = hls(acc)[0]


def pastel(hexa, l=0.80, smin=0.45, smax=0.85):
    """Catppuccin's accents are light (L~0.78-0.86) and soft. Keep the hue."""
    h, _, s = hls(hexa)
    if s < 0.15:                 # grey palette entry: borrow the accent's hue
        h, s = ah, 0.6
    return hx(h, l, min(smax, max(smin, s)))


def tone(hue_deg, l=0.80, s=0.65):
    return hx(hue_deg / 360, l, s)


text = pastel(acc, 0.82)
fh, fl, fs = hls(sp["foreground"])
subtext = hx(fh, max(fl, 0.84), min(fs, 0.25))

# Named pastels: the palette's own colours where they exist, so the accent
# picker in Spotify's settings (Catppuccin section) offers the wallpaper's
# colours; the in-between names are hue shifts of the nearest one.
red, green, yellow = pastel(c["color1"]), pastel(c["color2"]), pastel(c["color3"])
blue, mauve, teal = pastel(c["color4"]), pastel(c["color5"]), pastel(c["color6"])

v = {
    # Spicetify
    "text": text,
    "subtext": subtext,
    "main": layer(0),
    "main-elevated": layer(0.06),
    "highlight": layer(0.06),
    "highlight-elevated": layer(0.11),
    "sidebar": layer(-0.025),
    "player": layer(-0.045),
    "card": layer(0.06),
    "shadow": layer(-0.025),
    "selected-row": layer(0.45, 0.4),
    "button": layer(0.35, 0.3),
    "button-active": text,
    "button-disabled": layer(0.25, 0.3),
    "tab-active": layer(0.06),
    "notification": layer(0.06),
    "notification-error": red,
    "equalizer": "000000",
    "misc": layer(0.11),
    # Catppuccin
    "crust": layer(-0.045),
    "mantle": layer(-0.025),
    "base": layer(0),
    "surface0": layer(0.06),
    "surface1": layer(0.11),
    "surface2": layer(0.16, 0.1),
    "overlay0": layer(0.25, 0.3),
    "overlay1": layer(0.35, 0.3),
    "overlay2": layer(0.45, 0.4),
    "rosewater": pastel(c["color1"], 0.90, 0.3, 0.6),
    "flamingo": pastel(c["color1"], 0.86, 0.35, 0.7),
    "pink": pastel(c["color5"], 0.86),
    "maroon": pastel(c["color1"], 0.76),
    "red": red,
    "peach": pastel(c["color3"], 0.76),
    "yellow": yellow,
    "green": green,
    "teal": teal,
    "sapphire": pastel(c["color6"], 0.74),
    "blue": blue,
    "sky": pastel(c["color6"], 0.84),
    "mauve": mauve,
    "lavender": pastel(c["color4"], 0.86),
}

body = "".join("%-18s = %s\n" % kv for kv in v.items())
section = ("[pywal]\n; Generated by spicetify-catppuccin.py from "
           "~/.cache/wal/colors.json; do not edit by hand\n" + body)

# color.ini is generated (git-ignored): the stock flavours come from
# color.base.ini, versioned next to it, and the [pywal] block is added here.
BASE = os.path.join(os.path.dirname(OUT), "color.base.ini")
try:
    old = open(BASE).read()
except OSError:
    try:
        old = open(OUT).read()
    except OSError:
        old = ""
pat = re.compile(r"^\[pywal\][^\[]*", re.M)
new = pat.sub(lambda _: section + "\n", old, count=1) if pat.search(old) else \
    (old.rstrip("\n") + "\n\n" + section if old.strip() else section)
tmp = OUT + ".tmp"
with open(tmp, "w") as fh:
    fh.write(new)
os.replace(tmp, OUT)
