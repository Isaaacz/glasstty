#!/usr/bin/env bash
# uninstall-niri.sh — undo install-niri.sh.
#
#   ./uninstall-niri.sh            remove glasstty from ~/.config and friends
#   ./uninstall-niri.sh --dry-run  print what would be done, change nothing
#
# Removes only what is provably glasstty's:
#   * links that point into THIS repo (a link of yours elsewhere is left);
#   * copies that are still byte-for-byte the repo's file (one you edited stays);
#   * files the shell generates, recognised by their own marker (niri effect
#     files, the tinted icon themes) — never a whole folder by name alone.
# When the installer had moved something of yours aside (*.bak-<date>: a file,
# a folder or a link), the newest one is put back.
# Packages, pywal's cache, your wallpapers, your palette choices and the repo
# itself stay.
set -euo pipefail

repo="$(cd "$(dirname "$0")" && pwd)"
cfg="$HOME/.config"
dry=0
case "${1:-}" in
    "") ;;
    --dry-run) dry=1 ;;
    *) echo "usage: $0 [--dry-run]" >&2; exit 1 ;;
esac
[ "$(id -u)" -ne 0 ] || { echo "run this as your user, not with sudo" >&2; exit 1; }

say() { printf '\033[1;35m==>\033[0m %s\n' "$*"; }
run() { if [ "$dry" = 1 ]; then printf '    %s\n' "$*"; else "$@"; fi; }
removed=0; restored=0; kept=()

# Put back the newest backup of $1, if there is one and the place is free.
restore() {
    local p="$1" bak
    [ -e "$p" ] || [ -L "$p" ] && return 0
    bak="$(ls -d "$p".bak-* 2>/dev/null | sort | tail -n1 || true)"
    [ -n "$bak" ] || return 0
    run mv -- "$bak" "$p"
    say "restored: $p (from $(basename "$bak"))"
    restored=$((restored + 1))
}

# A link into the repo: remove it and bring back the newest backup, if any.
unlink_repo() {
    local p="$1"
    if [ -L "$p" ] && [[ "$(readlink -f "$p")" == "$repo"/* ]]; then
        run rm -- "$p"
        say "removed link: $p"
        removed=$((removed + 1))
        restore "$p"
    elif [ -e "$p" ] || [ -L "$p" ]; then
        kept+=("$p (not a link into this repo)")
    fi
}
# A copy of a repo file: remove it only if it is still identical.
remove_copy() {   # remove_copy <installed file> <repo file>
    if [ -f "$1" ] && [ ! -L "$1" ] && [ -f "$2" ] && cmp -s "$1" "$2"; then
        run rm -- "$1"
        say "removed: $1"
        removed=$((removed + 1))
        restore "$1"
    elif [ -e "$1" ]; then
        kept+=("$1 (you changed it)")
    fi
}
# A generated file: removed only if its first line carries our marker.
remove_marked() {  # remove_marked <file> <text its first line contains>
    [ -f "$1" ] && [ ! -L "$1" ] || return 0
    if head -n1 "$1" | grep -qF -- "$2"; then
        run rm -- "$1"; say "removed: $1"; removed=$((removed + 1))
    else
        kept+=("$1 (no glasstty marker)")
    fi
}

for p in quickshell niri/config.kdl quickshell-rice.json glasstty kitty fastfetch \
         spicetify/Themes spicetify/Extensions; do
    unlink_repo "$cfg/$p"
done
for b in "$repo"/home/.local/bin/*; do
    p="$HOME/.local/bin/$(basename "$b")"
    [ -L "$p" ] && [[ "$(readlink -f "$p")" == "$repo"/* ]] && unlink_repo "$p"
done

sd="$cfg/systemd/user"
remove_copy "$sd/niri.service.d/oo7.conf"       "$repo/home/.config/systemd/user/niri.service.d/oo7.conf"
remove_copy "$sd/niri.service.d/theme-env.conf" "$repo/home/.config/systemd/user/niri.service.d/theme-env.conf"
for s in xdg-desktop-portal-gnome xdg-desktop-portal-gtk; do
    remove_copy "$sd/$s.service.d/pocket-niri.conf" "$repo/home/.config/systemd/user/$s.service.d/pocket-niri.conf"
done
[ "$dry" = 1 ] || systemctl --user daemon-reload 2>/dev/null || true

for d in org.gnome.Settings.desktop pocket-dots-ajustes.desktop com.spotify.Client.desktop; do
    remove_copy "$HOME/.local/share/applications/$d" "$repo/home/.local/share/applications/$d"
done
remove_copy "$cfg/niri-mimeapps.list" "$repo/home/.config/niri-mimeapps.list"
for t in "$repo"/home/.config/wal/templates/*; do
    remove_copy "$cfg/wal/templates/$(basename "$t")" "$t"
done

# ── what the shell generated at run time ──
# niri effect files written by Settings > Appearance > Effects.
for f in "$cfg"/niri/efeitos.kdl "$cfg"/niri/efeitos-*.kdl; do
    remove_marked "$f" "// Generated by Settings"
done
# The niri-only icon theme: pywal-icons is a link to one of the generated
# pywal-folders-* themes (gtk-pywal.sh / folders-pywal.py).
icons="$HOME/.local/share/icons"
if [ -L "$icons/pywal-icons" ]; then
    run rm -- "$icons/pywal-icons"; say "removed link: $icons/pywal-icons"; removed=$((removed + 1))
fi
for d in "$icons"/pywal-folders-*; do
    [ -d "$d" ] && [ ! -L "$d" ] || continue
    if grep -q '^Comment=Folders tinted by pywal (generated' "$d/index.theme" 2>/dev/null; then
        run rm -r -- "$d"; say "removed: $d"; removed=$((removed + 1))
    else
        kept+=("$d (no glasstty marker)")
    fi
done
# The dconf profile dconf-niri.sh writes for the niri session: only its own files.
dc="$cfg/pocket-dots/dconf"
for f in "$dc/profile" "$dc/env" "$dc/niri.db" "$dc/niri.d/00-icons" "$dc/niri.d/locks/icons"; do
    if [ -f "$f" ] && [ ! -L "$f" ]; then run rm -- "$f"; say "removed: $f"; removed=$((removed + 1)); fi
done

# Folders the installer created and that are now empty.
for d in "$dc/niri.d/locks" "$dc/niri.d" "$dc" "$cfg/niri" "$sd"/niri.service.d "$sd"/xdg-desktop-portal-gnome.service.d \
         "$sd"/xdg-desktop-portal-gtk.service.d "$cfg/spicetify" "$cfg/wal/templates" "$cfg/wal"; do
    if [ -d "$d" ] && [ ! -L "$d" ] && [ -z "$(ls -A "$d")" ]; then run rmdir -- "$d"; fi
done

echo
say "Summary: removed $removed, restored $restored"
if [ "${#kept[@]}" -gt 0 ]; then
    printf '    left in place:\n'; printf '      %s\n' "${kept[@]}"
fi
if [ "$dry" = 1 ]; then
    say "Dry run: nothing was changed."
else
    say "Done. Packages, wallpapers and this repo were left in place."
    say "~/.config/niri/ keeps niri's own files; with config.kdl gone, niri uses its defaults."
fi
